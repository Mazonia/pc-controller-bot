def test_network_ip_and_subnet_format():
    """Verify IP and subnet parsing functions return valid formats."""
    ip = get_local_ip()
    parts = ip.split(".")
    assert len(parts) == 4
    for p in parts:
        assert p.isdigit()
        assert 0 <= int(p) <= 255

    subnet = get_subnet()
    sub_parts = subnet.split(".")
    assert len(sub_parts) == 3
    for p in sub_parts:
        assert p.isdigit()
        assert 0 <= int(p) <= 255


