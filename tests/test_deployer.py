def test_portable_installer_simulation(tmp_path):
    """Simulate the end-to-end installer workflow on a target PC in an isolated sandbox."""
    import json
    import shutil

    # 1. Setup mock source (simulating USB/SSD)
    src_dir = tmp_path / "ssd"
    src_dir.mkdir()
    for f in AGENT_CORE_FILES:
        shutil.copy2(os.path.join(DEPLOY_DIR, f), src_dir / f)

    fleet_file = src_dir / "fleet.json"
    fleet_file.write_text(json.dumps({"secret": "test-secret", "pcs": []}), encoding="utf-8")

    # 2. Simulate destination setup (C:\PCSentinel)
    dest_dir = tmp_path / "PCSentinel"
    dest_dir.mkdir()
    (dest_dir / "recordings").mkdir()
    (dest_dir / "downloads").mkdir()

    for f in ["agent.py", "fleet_relay.py", "system_controller.py", "screen_caster.py", "start_agent.bat", "start_agent_hidden.vbs"]:
        shutil.copy2(src_dir / f, dest_dir / f)

    # 3. Simulate agent.env generation from deploy_config.env
    env_lines = ["# Generated by installer test", "PC_NAME=MOCK-TARGET-PC"]
    with open(src_dir / "deploy_config.env", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                env_lines.append(line)
    (dest_dir / "agent.env").write_text("\n".join(env_lines), encoding="utf-8")

    # 4. Simulate fleet.json registration
    data = json.loads(fleet_file.read_text(encoding="utf-8"))
    data.setdefault("pcs", []).append({
        "name": "MOCK-TARGET-PC",
        "label": "MOCK-TARGET-PC",
        "ip": "127.0.0.1",
        "network": "Remote/LAN"
    })
    fleet_file.write_text(json.dumps(data, indent=4), encoding="utf-8")

    # 5. Verify the generated agent environment
    generated_env = (dest_dir / "agent.env").read_text(encoding="utf-8")
    assert "PC_NAME=MOCK-TARGET-PC" in generated_env
    assert "TELEGRAM_BOT_TOKEN=" in generated_env
    assert "FLEET_SECRET=" in generated_env
    assert "MQTT_BROKER=" in generated_env

    # 6. Verify fleet.json registered the target PC
    updated_fleet = json.loads(fleet_file.read_text(encoding="utf-8"))
    assert any(p["name"] == "MOCK-TARGET-PC" for p in updated_fleet["pcs"])

    # 7. Verify all core files exist in target install dir
    assert (dest_dir / "agent.py").exists()
    assert (dest_dir / "fleet_relay.py").exists()
    assert (dest_dir / "system_controller.py").exists()
    assert (dest_dir / "screen_caster.py").exists()
    assert (dest_dir / "start_agent.bat").exists()
    assert (dest_dir / "start_agent_hidden.vbs").exists()


def test_batch_syntax_and_quotes():
    """Verify that all batch files have balanced quotes and no broken multi-line python calls."""
    batch_files = ["1-CLICK-INSTALL.bat", "install.bat", "start_agent.bat", "uninstall.bat"]
    for b in batch_files:
        path = os.path.join(DEPLOY_DIR, b)
        assert os.path.exists(path), f"Batch file {b} missing"
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            lines = f.readlines()
        
        # Check that no lines have unclosed quotes when invoking python -c
        for idx, line in enumerate(lines, 1):
            stripped = line.strip()
            if '-c "' in stripped:
                assert stripped.count('"') % 2 == 0, (
                    f"{b}:{idx} has unclosed python -c quote (multi-line batch bug): {stripped}"
                )


def test_portable_desktop_folder_integrity():
    """Verify the Desktop PC-Sentinel-SSD-Installer folder if present is complete and ready."""
    desktop_folder = Path(r"C:\Users\Mazonia\Desktop\PC-Sentinel-SSD-Installer")
    if not desktop_folder.exists():
        pytest.skip("Desktop installer folder not present in current test environment")

    # Verify all core files
    for filename in AGENT_CORE_FILES:
        target = desktop_folder / filename
        assert target.exists(), f"Missing required file in Desktop portable installer: {filename}"
        assert target.stat().st_size > 0, f"File {filename} is empty in Desktop portable installer"

    # Verify Python installers if present
    py_installer = desktop_folder / "python-installer.exe"
    if py_installer.exists():
        assert py_installer.stat().st_size > 10_000_000, "python-installer.exe is too small/corrupted"

    cf_installer = desktop_folder / "cloudflared.exe"
    if cf_installer.exists():
        assert cf_installer.stat().st_size > 20_000_000, "cloudflared.exe is too small/corrupted"

    # Verify offline wheels if present
    wheels_dir = desktop_folder / "wheels"
    if wheels_dir.exists():
        wheels = list(wheels_dir.glob("*.whl"))
        assert len(wheels) > 0, "wheels directory exists but contains no .whl files"


